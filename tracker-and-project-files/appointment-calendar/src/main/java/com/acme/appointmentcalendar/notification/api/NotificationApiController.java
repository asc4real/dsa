package com.acme.appointmentcalendar.notification.api;

import com.acme.appointmentcalendar.OperationRouter;
import org.springframework.web.bind.annotation.*;
import org.springframework.http.*;
import java.net.URI;
import jakarta.servlet.http.HttpServletRequest;
import java.util.*;
@RestController
public class NotificationApiController {
 private final OperationRouter operations;
 public NotificationApiController(OperationRouter operations){this.operations=operations;}
 @RequestMapping(path="/api/v1/organizations/{orgId}/reminder-definitions",method=RequestMethod.GET)
 public ResponseEntity<?> listReminderDefinitions(
    @PathVariable Map<String,String> path,
    @RequestBody(required=false) Map<String,Object> body,
    @RequestHeader(name="Idempotency-Key",required=false) String idem,
    @RequestHeader(name="If-Match",required=false) String match,
    @RequestParam(name="limit",defaultValue="20") int limit,
    HttpServletRequest servletRequest,
    @RequestParam Map<String,String> query) {
  Object result=operations.route("listReminderDefinitions",path,body,match,idem,limit,query);
  if(result instanceof Map<?,?> value && value.get("version")!=null) return ResponseEntity.ok().eTag("\"v"+value.get("version")+"\"").body(result);
  return ResponseEntity.ok(result);
 }
 @RequestMapping(path="/api/v1/organizations/{orgId}/reminder-definitions",method=RequestMethod.POST)
 public ResponseEntity<?> createReminderDefinition(
    @PathVariable Map<String,String> path,
    @RequestBody(required=false) Map<String,Object> body,
    @RequestHeader(name="Idempotency-Key",required=false) String idem,
    @RequestHeader(name="If-Match",required=false) String match,
    @RequestParam(name="limit",defaultValue="20") int limit,
    HttpServletRequest servletRequest,
    @RequestParam Map<String,String> query) {
  Object result=operations.route("createReminderDefinition",path,body,match,idem,limit,query);
  if(result instanceof Map<?,?> value && value.get("id")!=null) return ResponseEntity.created(URI.create(servletRequest.getRequestURI()+"/"+value.get("id"))).body(result);
  return ResponseEntity.status(201).body(result);
 }
 @RequestMapping(path="/api/v1/organizations/{orgId}/reminder-definitions/{reminderId}",method=RequestMethod.PATCH)
 public ResponseEntity<?> updateReminderDefinition(
    @PathVariable Map<String,String> path,
    @RequestBody(required=false) Map<String,Object> body,
    @RequestHeader(name="Idempotency-Key",required=false) String idem,
    @RequestHeader(name="If-Match",required=false) String match,
    @RequestParam(name="limit",defaultValue="20") int limit,
    HttpServletRequest servletRequest,
    @RequestParam Map<String,String> query) {
  Object result=operations.route("updateReminderDefinition",path,body,match,idem,limit,query);
  if(result instanceof Map<?,?> value && value.get("version")!=null) return ResponseEntity.ok().eTag("\"v"+value.get("version")+"\"").body(result);
  return ResponseEntity.ok(result);
 }
 @RequestMapping(path="/api/v1/organizations/{orgId}/appointments/{appointmentId}/notifications",method=RequestMethod.GET)
 public ResponseEntity<?> listAppointmentNotifications(
    @PathVariable Map<String,String> path,
    @RequestBody(required=false) Map<String,Object> body,
    @RequestHeader(name="Idempotency-Key",required=false) String idem,
    @RequestHeader(name="If-Match",required=false) String match,
    @RequestParam(name="limit",defaultValue="20") int limit,
    HttpServletRequest servletRequest,
    @RequestParam Map<String,String> query) {
  Object result=operations.route("listAppointmentNotifications",path,body,match,idem,limit,query);
  if(result instanceof Map<?,?> value && value.get("version")!=null) return ResponseEntity.ok().eTag("\"v"+value.get("version")+"\"").body(result);
  return ResponseEntity.ok(result);
 }

}
